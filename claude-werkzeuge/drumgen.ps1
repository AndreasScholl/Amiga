param([string]$f, [string]$out)
# the song's drum channel (3), step by step (16 a bar, a step every 6 ticks from tick 1), as
# drum hits: instrument (sample offset in LSPBank, length, period, volume) -> drumseq.i
$ev = Get-Content $f | ? { $_ -match '^N ' } | % { $a = $_ -split ' '; [pscustomobject]@{ t = [int]$a[1]; c = [int]$a[2]; s = [int]$a[3]; l = [int]$a[4]; p = [int]$a[5]; v = [int]$a[6] } } | ? { $_.c -eq 3 -and $_.t -lt 12288 -and $_.s -ne 4 }
$ins = @(); $insKey = @{}
$bars = @{}
$off = 0
foreach ($e in $ev) {
  $r = ($e.t - 1) % 6; if ($r -ne 0) { $off++ }
  $b = [int][math]::Floor(($e.t - 1) / 96); $st = [int][math]::Floor((($e.t - 1) % 96) / 6)
  $k = "$($e.s),$($e.l),$($e.p),$($e.v)"
  if (-not $insKey.ContainsKey($k)) { $ins += $k; $insKey[$k] = $ins.Count }
  if (-not $bars.ContainsKey($b)) { $bars[$b] = New-Object int[] 16 }
  $bars[$b][$st] = $insKey[$k]
}
$pats = @(); $patKey = @{}; $map = @()
for ($b = 0; $b -lt 128; $b++) {
  $p = if ($bars.ContainsKey($b)) { $bars[$b] } else { New-Object int[] 16 }
  $k = ($p -join ',')
  if (-not $patKey.ContainsKey($k)) { $patKey[$k] = $pats.Count; $pats += $k }
  $map += $patKey[$k]
}
"off-grid events: $off, instruments: $($ins.Count), patterns: $($pats.Count)"
$o = @('; generated by drumgen.ps1 (scratchpad) from the CopperCabana score: its drums',
       '; (channel 3) for music.s drumSeq - the same samples, periods, volumes',
       '; instruments: offset in LSPBank, length (words), period, volume, the',
       '; channel (DMACON bit: the hi-hats on 2, the rest on 0)')
$o += 'dsIns:'
foreach ($k in $ins) { $q = $k -split ','; $ch = if ($q[0] -eq '15634') { 4 } else { 1 }; $o += "`t`tdc.w`t$($q[0]),$($q[1]),$($q[2]),$($q[3]),$ch" }
$o += '; patterns: 16 steps a bar (a step every 6 ticks), 0 none, else an instrument'
$o += 'dsPat:'
foreach ($k in $pats) { $o += "`t`tdc.b`t$k" }
$o += '; the song''s 128 bars: their pattern'
$o += 'dsBar:'
for ($i = 0; $i -lt 128; $i += 16) { $o += "`t`tdc.b`t" + (($map[$i..($i + 15)]) -join ',') }
$o += "`t`teven"
[IO.File]::WriteAllText($out, ($o -join "`r`n") + "`r`n")
for ($i = 0; $i -lt $pats.Count; $i++) { "{0,2}: {1}" -f $i, $pats[$i] }
"map: " + ($map -join ' ')
for ($i = 0; $i -lt $ins.Count; $i++) { "ins {0}: {1}" -f ($i + 1), $ins[$i] }
