# abgen.py - the afterburner's chain of glows (morph.i morphChain) -> abflame.i
#
# four kinds of blob, one for each sprite of the chain along the thrust axis:
#   0 the nozzle: a white core, light yellow, a yellow rim (colours 17, 18, 19)
#   1 light yellow, a yellow rim, a little ragged        (17-19 as well)
#   2 orange, red, a dark red rim                        (21, 22, 23)
#   3 the tip: red, dark red, airy - about 35 % of it holes
# each in abFrames animation frames (the rim ragged differently) and R 1..7
# (a sprite is 16 wide: the middle on its column 7). a row is two words,
# plane A and B: the colour's bit 0 and bit 1.
# layout: kind, frame, R - R's rows from R*R-1 on (2R+1 rows each, 63 a frame)

import random

FRAMES = 4
RMAX = 7
rnd = random.Random(0xAB5EED)

# (core bound, middle bound) as fractions of R: inside the core colour 1,
# then 2, then 3 out to the rim; the rim's raggedness; the holes
KINDS = [
    dict(core=0.45, mid=0.75, rag=0.10, holes=0.00, base=(1, 2, 3)),
    dict(core=0.00, mid=0.45, rag=0.18, holes=0.05, base=(1, 2, 3)),
    dict(core=0.40, mid=0.72, rag=0.20, holes=0.08, base=(1, 2, 3)),
    dict(core=0.00, mid=0.40, rag=0.28, holes=0.35, base=(1, 2, 3)),
]


def blob(kind, r):
    k = KINDS[kind]
    rows = []
    for dy in range(-r, r + 1):
        a = b = 0
        for col in range(16):
            dx = col - 7
            d = (dx * dx + dy * dy) ** 0.5
            reach = (r + 0.5) * (1.0 - k['rag'] + 2 * k['rag'] * rnd.random())
            if d > reach:
                continue
            if rnd.random() < k['holes'] and d > 0.3 * r:
                continue
            t = d / (r + 0.5)
            if kind == 1 or kind == 3:
                c = 2 if t < k['mid'] else 3
            else:
                c = 1 if t < k['core'] else (2 if t < k['mid'] else 3)
            if r == 1 and dx == 0 and dy == 0:
                c = 1 if kind in (0, 2) else 2
            bit = 15 - col
            if c & 1:
                a |= 1 << bit
            if c & 2:
                b |= 1 << bit
        rows.append((a, b))
    return rows


out = ['; generated by abgen.py - the afterburner\'s chain of glows (morph.i',
       '; morphChain): 4 kinds x abFrames frames x R 1..7, rows of plane A, B',
       'abFrames\t= %d' % FRAMES,
       'abImg:']
for kind in range(4):
    for f in range(FRAMES):
        words = []
        for r in range(1, RMAX + 1):
            for a, b in blob(kind, r):
                words += [a, b]
        for i in range(0, len(words), 16):
            out.append('\t\tdc.w\t' + ','.join('$%04x' % w for w in words[i:i + 16]))
open('abflame.i', 'w', newline='\r\n').write('\n'.join(out) + '\n')
print('abflame.i: %d bytes of data' % (4 * FRAMES * 63 * 4))
